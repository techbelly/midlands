// Runs at demo build time (node): compiles the Nile text pipeline and writes
// the generated JS out as a plain module. The browser never sees the compiler
// — just its output, which is ordinary data.

import { writeFileSync } from 'node:fs';
import { compileTextPipeline } from '../src/text/render.js';
import { compileVectorPipeline } from '../src/vector/compile.js';
import { textSpansParams, driveTextSpans } from '../src/text/host.js';
import * as rt from '../../umgeni/src/cpu/runtime.js';

const t0 = performance.now();
// This file executes as a bundle at demos/gen/.gen-entry.mjs, so the
// midlands root is two levels up from its runtime location.
const root = new URL('../../', import.meta.url);
const program = compileTextPipeline(root);
const compileMs = performance.now() - t0;

if (program.unsupported.length > 0) {
  throw new Error(`unsupported processes: ${JSON.stringify(program.unsupported)}`);
}

// Smoke-test the exact artifact the demo will use.
const registry = new Function('rt', `return (${program.source})(rt);`)(rt);
const op = registry['TextSpans'](textSpansParams({ size: 14, width: 200, height: 40 }));
const { spans } = driveTextSpans(op, 'HELLO WORLD');
if (spans.length < 50) throw new Error(`smoke test produced only ${spans.length} spans`);

const out = new URL('pipeline.gen.js', import.meta.url);
writeFileSync(
  out,
  [
    '// GENERATED by demos/tools/build.mjs — umgeni\'s JS output',
    '// for demos/nl/text.nl + the gezira kernels. Do not edit.',
    `export const compileMs = ${compileMs.toFixed(1)};`,
    `export const makeRegistry = ${program.source};`,
    '// Rasterize2 as plain fused IR data: the browser lowers it to WGSL itself.',
    `export const rasterize2IR = ${JSON.stringify(
      program.ir.processes.find((p) => p.k === 'fused' && p.name === 'Rasterize2'),
    )};`,
    '',
  ].join('\n'),
);
console.log(`pipeline.gen.js written (compiled in ${compileMs.toFixed(1)} ms, smoke: ${spans.length} spans)`);

// The vector demos (tiger, strokes): gezira's own kernels (stroke.nl
// unmodified) + demos/nl/vector.nl + svg.nl, compiled into their own registry module.
const vector = compileVectorPipeline(root);
if (vector.unsupported.length > 0) {
  throw new Error(`vector kernels unsupported: ${JSON.stringify(vector.unsupported)}`);
}
writeFileSync(
  new URL('vector.gen.js', import.meta.url),
  [
    '// GENERATED by demos/tools/build.mjs — umgeni-compiled gezira kernels',
    '// (types/bezier/stroke/rasterize.nl) + demos/nl/{vector,svg}.nl. Do not edit.',
    `export const makeVectorRegistry = ${vector.source};`,
    '',
  ].join('\n'),
);
console.log(`vector.gen.js written (${vector.registry.size} processes)`);
