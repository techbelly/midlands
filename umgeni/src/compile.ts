// The whole toolchain, end to end:
//   source text -> parse -> AST -> elaborate -> IR -> fuse, fold, CSE, prune, tail
//     -> generate -> JS (with wasm modules inside, when asked) -> Ops
//
// compileLibrary exposes every intermediate stage as data (AST, IR, generated
// source), in keeping with the project's inspectability principle.

import type * as ast from './ast.js';
import { parseProgram } from './parser.js';
import { elaborateProgram } from './elaborate.js';
import { generate, type CodegenOptions } from './cpu/js.js';
import { cseModule } from './passes/cse.js';
import { foldModule, pruneModule } from './passes/simplify.js';
import { fuseModule } from './passes/fuse.js';
import { tailModule } from './passes/tail.js';
import type { ModuleIR } from './ir.js';
import * as rt from './cpu/runtime.js';

// The passes default on: measured on the paragraph benchmark
// (demos/tools/bench.ts) the scalar passes cut executed IR ops ~23%, static
// IR ops ~38%, and generated bytes ~10%, with span-identical output. JS
// wall-clock barely moves (V8 was already doing similar work); the wins are
// code size, IR-level cost, and future non-JIT targets.
export interface CompileOptions extends CodegenOptions {
  /** Run the scalar passes: constant folding, common-subexpression
   *  elimination and dead-let pruning (passes/simplify.ts, passes/cse.ts).
   *  Default true. */
  cse?: boolean;
  /** Fuse pipeline stages (stream-level; runs before CSE). Default true:
   *  measured −11% wall on the paragraph benchmark (it removes inter-stage
   *  token arrays and queues, a cost the dyn-ops metric cannot see), at the
   *  price of larger generated source (stage kernels are embedded). */
  fuse?: boolean;
  /** Mark feeds in tail position, so a back end loops instead of pushing
   *  and popping (passes/tail.ts). Default true: measured −9% wall on the
   *  paragraph benchmark's JS build, output identical. */
  tail?: boolean;
}

export interface CompiledLibrary {
  /** The library as a host uses it: nile.SvgFill({ … }).run(tokens), nile.types.Point. */
  api: rt.Api;
  /** The generated JS source (inspectable). */
  source: string;
  /** Processes with process-typed parameters: instantiated at each use. */
  templates: string[];
  /** Processes the elaborator could not handle, with reasons. */
  unsupported: { name: string; reason: string }[];
  ir: ModuleIR;
  modules: ast.Module[];
  /** Dynamic IR-operation counter (present when compiled with countOps). */
  ops?: () => number;
}

export function compileLibrary(sources: string[], opts: CompileOptions = {}): CompiledLibrary {
  const { modules } = parseProgram(sources);
  const elaborated = elaborateProgram(modules);
  // Pass order: structural (fusion) before scalar, one run each. Folding
  // goes before CSE so its keys see folded constants; pruning after, since
  // CSE's own lets can be the last readers of a dead one.
  let ir = elaborated.ir;
  if (opts.fuse ?? true) ir = fuseModule(ir);
  if (opts.cse ?? true) ir = pruneModule(cseModule(foldModule(ir)));
  if (opts.tail ?? true) ir = tailModule(ir);
  const source = generate(ir, { ...opts, boolCond: opts.boolCond ?? true });
  // The generated record: each process's factory by name, and under symbols
  // its token layouts, host-process slots and (with countOps) its counter.
  // eslint-disable-next-line @typescript-eslint/no-implied-eval
  const R = new Function('rt', `return (${source})(rt);`)(rt) as Record<string, rt.Factory>;
  return { api: rt.api(R), source, unsupported: elaborated.unsupported, templates: elaborated.templates, ir, modules, ops: rt.opsCounter(R) };
}

// Convenience: instantiate one process and drive it via a Streamer.
export function makeStreamer(library: CompiledLibrary, name: string, params: rt.Params = []): rt.Streamer {
  if (!(name in library.api)) throw new Error(`no process named '${name}' (unsupported? ${library.unsupported.map((u) => u.name).join(', ') || 'none'})`);
  return rt.streamer(library.api[name](params));
}
