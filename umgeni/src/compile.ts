// The whole toolchain, end to end:
//   source text -> parse -> AST -> elaborate -> IR -> generate -> JS -> Ops
//
// compileProgram exposes every intermediate stage as data (AST, IR, generated
// source), in keeping with the project's inspectability principle.

import type * as ast from './ast.js';
import { parseProgram } from './parser.js';
import { elaborateProgram } from './elaborate.js';
import { generate, type CodegenOptions } from './cpu/js.js';
import { cseModule } from './passes/cse.js';
import { fuseModule } from './passes/fuse.js';
import type { ModuleIR } from './ir.js';
import * as rt from './cpu/runtime.js';

export type ProcessFactory = (params?: number[]) => rt.Op;

// Both optimizations default on: measured on the paragraph benchmark
// (tools/bench.ts) they cut executed IR ops ~8%, static IR ops ~21%, and
// generated bytes ~15%, with span-identical output. JS wall-clock barely
// moves (V8 was already doing similar work); the wins are code size,
// IR-level cost, and future non-JIT targets.
export interface CompileOptions extends CodegenOptions {
  /** Run common-subexpression elimination on the IR. Default true. */
  cse?: boolean;
  /** Fuse pipeline stages (stream-level; runs before CSE). Default true:
   *  measured −11% wall on the paragraph benchmark (it removes inter-stage
   *  token arrays and queues, a cost the dyn-ops metric cannot see), at the
   *  price of larger generated source (stage kernels are embedded). */
  fuse?: boolean;
}

export interface CompiledProgram {
  /** Instantiate a process by name with its flattened parameter vector. */
  registry: Map<string, ProcessFactory>;
  /** The generated JS source (inspectable). */
  source: string;
  /** Processes with process-typed parameters: instantiated at each use. */
  templates: string[];
  /** Processes the elaborator could not handle, with reasons. */
  unsupported: { name: string; reason: string }[];
  ir: ModuleIR;
  modules: ast.Module[];
  /** Dynamic IR-operation counter (present when compiled with countOps). */
  ops?: () => number;
}

export function compileProgram(sources: string[], opts: CompileOptions = {}): CompiledProgram {
  const { modules } = parseProgram(sources);
  const elaborated = elaborateProgram(modules);
  // Pass order: structural (fusion) before scalar (CSE), one run each.
  let ir = elaborated.ir;
  if (opts.fuse ?? true) ir = fuseModule(ir);
  if (opts.cse ?? true) ir = cseModule(ir);
  const source = generate(ir, { boolCond: opts.boolCond ?? true, countOps: opts.countOps, target: opts.target });
  // eslint-disable-next-line @typescript-eslint/no-implied-eval
  const registryObj = new Function('rt', `return (${source})(rt);`)(rt) as Record<string, ProcessFactory>;
  const ops = (registryObj as Record<string, unknown>).__ops as (() => number) | undefined;
  delete (registryObj as Record<string, unknown>).__ops;
  const registry = new Map(Object.entries(registryObj));
  return { registry, source, unsupported: elaborated.unsupported, templates: elaborated.templates, ir, modules, ops };
}

// Convenience: instantiate one process and drive it via a Streamer.
export function makeStreamer(program: CompiledProgram, name: string, params: number[] = []): rt.Streamer {
  const factory = program.registry.get(name);
  if (!factory) throw new Error(`no process named '${name}' (unsupported? ${program.unsupported.map((u) => u.name).join(', ') || 'none'})`);
  return rt.streamer(factory(params));
}
